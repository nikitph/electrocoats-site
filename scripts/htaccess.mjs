// Writes public/.htaccess: 301s from every old electrocoats.com URL to its new home.
import { writeFileSync } from 'node:fs';
import { products } from '../src/data/products.ts';

const pages = {
  'index.html': '/', 'about.html': '/about/company-profile/', 'team.html': '/about/leadership/', 'achievement.html': '/about/achievements/',
  'client.html': '/clients/', 'testimonial.html': '/testimonials/', 'contact.html': '/contact/',
  'csr_policy.html': '/about/csr/', 'csr_projects.html': '/about/csr/', 'returns.html': '/about/annual-returns/',
};
for (const p of products) for (const old of p.legacy) pages[old] = `/products/${p.slug}/`;

const esc = (s) => s.replace(/[.]/g, '\\.');
const lines = Object.entries(pages).map(([from, to]) => `RewriteRule ^${esc(from)}$ ${to} [R=301,L,NC]`);
writeFileSync('public/.htaccess', `# Generated by scripts/htaccess.mjs — do not edit by hand.
Options -Indexes
ErrorDocument 404 /404.html
RewriteEngine On
RewriteCond %{HTTPS} off
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
RewriteRule ^ https://%1%{REQUEST_URI} [R=301,L]

# Legacy pages
${lines.join('\n')}

# Old template leftovers
RewriteRule ^(clean_old_files|PHPMailer-master)(/.*)?$ - [G,L]

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 month"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/jpeg "access plus 1 month"
</IfModule>
`);
console.log(`.htaccess: ${lines.length} redirects`);
